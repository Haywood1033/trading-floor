// Security and compliance: access, connections, kill switch history, compliance watch,
// full audit log, and fund data.

import * as D from '../desk.js';
import { esc, panel } from '../ui.js';

const KINDS = ['all', 'fill', 'signal', 'veto', 'reject', 'halt', 'paper', 'system'];

export function renderSecurity(s, ui) {
  const d = ui.drafts;
  const sy = ui.sync?.status || { mode: 'local' };
  const SETUP = {
    'storage-not-configured': 'Server storage is not connected yet. In Vercel: Storage → create an Upstash Redis database → connect it to this project.',
    'password-not-set': 'Storage is connected but no password is set. In Vercel: Settings → Environment Variables → add APP_PASSWORD.'
  };
  const loginCard = sy.mode === 'synced'
    ? `<div class="statecard"><b>Login and sync <span class="flag-ok">On</span></b>
        <span>The fund is stored on the server behind your password and shared by every device you sign in on. This device: ${esc(ui.sync.me)}.${ui.sync.otherRunning() ? ' The clock is currently running on another device.' : ''}</span>
        <div class="actions"><button class="btn" data-act="logout">Sign out on this device</button></div></div>`
    : `<div class="statecard"><b>Login and sync <span class="flag-warn">${sy.mode === 'login' ? 'Signed out' : sy.mode === 'error' ? 'Problem' : 'Not set up'}</span></b>
        <span>${esc(SETUP[sy.lastError] || (sy.mode === 'error' ? 'The server returned an error: ' + sy.lastError : sy.mode === 'login' ? 'Sign in to load the shared fund.' : 'This fund is saved in this browser only.'))}</span></div>`;
  const status = `
    ${loginCard}
    <div class="statecard"><b>Broker <span class="flag-off">None connected</span></b>
      <span>Every order fills in the simulation. A broker connection (for example Alpaca) comes in Phase 3, after paper validation.</span></div>
    <div class="statecard"><b>Market data <span class="flag-off">Simulated</span></b>
      <span>Prices are generated by a seeded simulator. Real daily prices come in Phase 2.</span></div>
    <div class="statecard"><b>Kill switch ${s.kill.halted ? `<span class="down">Halted since ${s.kill.at}</span>` : '<span class="flag-ok">Armed, trading active</span>'}</b>
      <span>Halting cancels pending orders and stops the quants until you resume. Open positions stay.</span>
      <div class="actions">${s.kill.halted ? '<button class="btn primary" data-act="resume">Resume trading</button>' : '<button class="btn danger" data-act="kill">Halt trading</button>'}</div></div>`;

  const killHist = s.log.filter(e => e.kind === 'halt' || /Trading resumed/.test(e.text)).slice(0, 20);
  const dayTrades = D.dayTradeLog(s);
  const L = s.settings.limits;
  const wash = D.washSaleWatch(s);
  const compliance = `
    <div class="statecard"><b>Day trades, last 5 trading days: ${dayTrades.length}${L.dayTradeLimit != null ? ` / ${L.dayTradeLimit}` : ''}</b>
      <span>${D.totals(s).equity >= L.dayTradeEquityThreshold ? `The day-trade cap only applies under ${D.usd(L.dayTradeEquityThreshold)} NAV, so it is not limiting this fund.` : 'The cap is enforced on every order.'}</span>
      ${dayTrades.length ? `<span>${dayTrades.map(x => `${x.symbol} on ${x.day}`).join(', ')}</span>` : ''}</div>
    <div class="statecard"><b>Wash-sale watch: ${wash.length} loss sale${wash.length === 1 ? '' : 's'} in the last 30 days</b>
      <span>Selling a stock at a loss and buying it back within 30 days means the loss doesn't count for taxes. Crypto is excluded.</span>
      ${wash.length ? `<div class="tablewrap"><table><thead><tr><th>Stock</th><th>Sold</th><th class="r">Loss</th><th>Rebought</th><th>Clear to rebuy</th></tr></thead><tbody>
        ${wash.map(w => `<tr><td class="sym">${w.symbol}</td><td class="num">${w.date}</td><td class="r num down">${D.usd(w.loss)}</td>
          <td class="${w.rebought ? 'warn' : 'muted'}">${w.rebought ? 'Yes, ' + w.rebought + ' (loss disallowed)' : 'No'}</td><td class="num">${w.clearOn}</td></tr>`).join('')}</tbody></table></div>` : ''}</div>`;

  const q = (d.logq || '').toLowerCase(), kind = d.logkind || 'all';
  const entries = s.log.filter(e => (kind === 'all' || e.kind === kind) && (!q || e.text.toLowerCase().includes(q) || e.at.includes(q)));
  const audit = `<div class="search"><input id="logq" data-draft placeholder="Search the log (symbol, date, word)" value="${esc(d.logq || '')}" aria-label="Search the log">
      <select id="logkind" data-draft aria-label="Entry type">${KINDS.map(k => `<option ${k === kind ? 'selected' : ''}>${k}</option>`).join('')}</select>
      <span class="muted num" style="align-self:center">${entries.length} of ${s.log.length}</span></div>
    ${entries.length ? `<ul class="log" style="max-height:520px">${entries.slice(0, 300).map(e => `<li><time>${e.at}</time><span class="tag ${e.kind}">${e.kind}</span><span>${esc(e.text)}</span></li>`).join('')}</ul>` : '<div class="empty">No entries match.</div>'}
    <div class="pad muted" style="font-size:12px">The log keeps the latest 500 entries in this browser.</div>`;

  const data = `<div class="pad" style="display:grid;gap:10px">
      <span class="muted">The fund lives in this browser only. Export saves a copy of everything (positions, orders, calls, log, settings) as a file.</span>
      <div class="actions"><button class="btn" data-act="export">Export fund data</button>
        <button class="btn danger" data-act="reset">Reset simulation</button></div></div>`;

  return `<div class="desk-head"><h1>Security</h1><p>Who can get in, what is connected, and the record of everything that happened.</p></div>
    <div class="cols-2">
      ${panel('Access and connections', '', status)}
      ${panel('Compliance', '', compliance)}
    </div>
    <div class="cols-2">
      ${panel('Kill switch history', `${killHist.length}`, killHist.length ? `<ul class="log">${killHist.map(e => `<li><time>${e.at}</time><span class="tag ${e.kind}">${e.kind}</span><span>${esc(e.text)}</span></li>`).join('')}</ul>` : '<div class="empty">Never used.</div>')}
      ${panel('Fund data', '', data)}
    </div>
    ${panel('Audit log', 'every signal, decision, fill and change', audit)}`;
}
